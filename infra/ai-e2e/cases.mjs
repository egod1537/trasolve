// Independent expected-state projection. Preserve every existing place field and ID.
// Route IDs/layout items are regenerated by the product; browser validation checks
// their references separately, and compares canonical state to the real Preview.
export function project(trip) {
  return {
    title: trip.title,
    days: trip.days.map((d) => ({
      id: d.id,
      title: d.title,
      places: d.places.map(({ order, ...p }) => p),
    })),
  };
}
export function expected(trip, id, phase = 'after') {
  const e = project(structuredClone(trip));
  const find = (name) =>
    e.days.flatMap((d) => d.places).find((p) => p.name === name);
  const move = (name, target) => {
    const p = find(name);
    for (const d of e.days) d.places = d.places.filter((x) => x !== p);
    target.places.push(p);
  };
  if (id === 'E2E-03' || (id === 'E2E-08' && phase === 'preview'))
    e.days[0].places.splice(1, 1);
  if (id === 'E2E-04') {
    const d = { id: '<new-day>', title: '서울 야경', places: [] };
    e.days.push(d);
    move('N서울타워', d);
    move('서울역', d);
    find('서울역').time = '20:00';
    find('서울역').visitDurationMinutes = 60;
    find('서울역').preferredDurationMinutes = 60;
  }
  if (id === 'E2E-05' || id === 'E2E-07') move('N서울타워', e.days[1]);
  if (id === 'E2E-06' || id === 'E2E-07') {
    find('명동').visitDurationMinutes = 60;
    find('명동').preferredDurationMinutes = 60;
  }
  if (id === 'E2E-07') find('봉은사').memo = '조용히 관람';
  if (id === 'E2E-10')
    e.title = phase === 'preview' ? '서울 3일 E2E-A' : '서울 3일 E2E-B';
  if (id === 'E2E-11')
    e.days.push({ id: '<new-day>', title: 'E2E 복구 확인', places: [] });
  return e;
}
